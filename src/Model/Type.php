<?php

namespace Rushing\Codegen\Model;

/**
 * A type reference in the semantic model — a {@see TypeKind} plus whatever detail that kind needs
 * (a {@see Primitive} for scalars, an inner {@see Type} for list/optional, a name for a record ref).
 * Value object with named constructors so authoring reads declaratively:
 *
 *   Type::primitive(Primitive::String)
 *   Type::listOf(Type::ref('User'))
 *   Type::optional(Type::primitive(Primitive::Int))
 *
 * Drivers pattern-match on `kind` to realize each idiomatically. Kept plain-mutable per house style
 * (no readonly/final); treat as immutable by convention.
 */
class Type
{
    /**
     * @param  Type[]  $variants  the member types of a union (kind = Union)
     */
    public function __construct(
        public TypeKind $kind,
        public ?Primitive $primitive = null,
        public ?Type $inner = null,
        public ?Type $value = null,
        public ?string $ref = null,
        public array $variants = [],
    ) {}

    public static function primitive(Primitive $primitive): static
    {
        return new static(TypeKind::Primitive, primitive: $primitive);
    }

    public static function ref(string $name): static
    {
        return new static(TypeKind::Ref, ref: $name);
    }

    /**
     * A reference to a type defined OUTSIDE this model — a host-supplied class or a type generated by
     * a different tool (e.g. `App.Data.User`, emitted by the spatie typescript-transform, or an
     * existing PHP DTO class). {@see CodegenModel::validate()} does not require these to resolve
     * against the model's own records/enums — that is the point: not everything a generator emits is
     * defined in the model.
     */
    public static function external(string $name): static
    {
        return new static(TypeKind::External, ref: $name);
    }

    public static function listOf(Type $inner): static
    {
        return new static(TypeKind::ListOf, inner: $inner);
    }

    /** A map keyed by string (the portable common denominator) to $value. */
    public static function mapOf(Type $value): static
    {
        return new static(TypeKind::MapOf, value: $value);
    }

    public static function optional(Type $inner): static
    {
        return new static(TypeKind::Optional, inner: $inner);
    }

    /**
     * A sum type — a value that is one of several {@see Type}s. A driver realizes it as a PHP union
     * type / TS union / Rust enum. Enum *values* (a fixed set of scalar cases) are a named
     * {@see EnumType} referenced via {@see Type::ref()}, not a union of primitives.
     *
     * @param  Type[]  $variants
     */
    public static function union(array $variants): static
    {
        return new static(TypeKind::Union, variants: array_values($variants));
    }

    /**
     * @return array<string, mixed>
     */
    public function toArray(): array
    {
        return array_filter([
            'kind' => $this->kind->value,
            'primitive' => $this->primitive?->value,
            'inner' => $this->inner?->toArray(),
            'value' => $this->value?->toArray(),
            'ref' => $this->ref,
            'variants' => $this->variants === []
                ? null
                : array_map(fn (Type $t) => $t->toArray(), $this->variants),
        ], fn ($v) => $v !== null);
    }
}
